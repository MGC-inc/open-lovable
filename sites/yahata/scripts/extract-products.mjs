/**
 * Regenerates data/products.ts from saved copies of the product taxonomy pages.
 *
 * Each body/option term has its own archive page listing a handful of built
 * vehicles: a hero shot, a name, a one-line spec and a grid of detail photos
 * with captions. That is pure catalogue data, so it is lifted into a typed
 * structure here rather than transcribed into JSX by hand.
 *
 *   node scripts/extract-products.mjs <mirror-root> <manifest-out>
 *
 * `mirror-root` is a local copy of www.yahata-sa.co.jp.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [, , mirrorRoot = ".", manifestOut = "product-assets.txt"] = process.argv;

const assets = new Set();

function localise(url) {
  const local = url.replace("https://www.yahata-sa.co.jp/", "/");
  if (local.startsWith("/wp/")) assets.add(local);
  return local;
}

/** Turns inline markup into plain lines, keeping <br> as a line break. */
function toLines(html) {
  return html
    .replace(/<br\s*\/?>/g, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
}

/** Reads the term cards (name, slug, thumbnail) out of the products index. */
function readTerms(html, group) {
  const section = html.match(new RegExp(`<section id="${group}">([\\s\\S]*?)</section>`));
  if (!section) throw new Error(`no <section id="${group}"> on the products page`);

  return [...section[1].matchAll(/<a href="[^"]*\/type\/[^/]+\/([^/]+)\/"[\s\S]*?<\/a>/g)].map((match) => {
    const [whole, slug] = match;
    const name = whole.match(/c-card_products_term__ttl">([^<]*)</)[1];
    const image = whole.match(/<img src="([^"]+)"/)[1];
    return { slug, name, image: localise(image) };
  });
}

/** Reads the vehicles listed on one term's archive page. */
function readVehicles(group, slug) {
  const html = readFileSync(join(mirrorRoot, "products", "type", group, slug, "index.html"), "utf8");

  return [...html.matchAll(/<section class="p-products_body">([\s\S]*?)<\/section>/g)].map((match) => {
    const block = match[1];
    const hero = block.match(/<figure class="p-products_body__img"><img src="([^"]+)" alt="([^"]*)"/);
    const name = block.match(/p-products_body__name">([\s\S]*?)<\/h2>/);
    const desc = block.match(/p-products_body__desc">([\s\S]*?)<\/div>/);
    const listBlock = block.match(/<ul class="p-products_body__list">([\s\S]*?)<\/ul>/);

    const details = listBlock
      ? [...listBlock[1].matchAll(/<li>([\s\S]*?)<\/li>/g)].map((item) => ({
          image: localise(item[1].match(/<img src="([^"]+)"/)[1]),
          captions: [...item[1].matchAll(/<p>([\s\S]*?)<\/p>/g)].map((p) => toLines(p[1]).join("\n"))
        }))
      : [];

    return {
      image: localise(hero[1]),
      alt: hero[2],
      name: toLines(name[1]).join(" "),
      description: desc ? toLines(desc[1]) : [],
      details
    };
  });
}

const indexHtml = readFileSync(join(mirrorRoot, "products", "index.html"), "utf8");

const categories = [
  { group: "body", en: "Body", ja: "ボデー" },
  { group: "option", en: "Option", ja: "オプション" }
].map((category) => ({
  ...category,
  terms: readTerms(indexHtml, category.group).map((term) => ({
    ...term,
    vehicles: readVehicles(category.group, term.slug)
  }))
}));

const file = `// Generated by scripts/extract-products.mjs — edit that script, not this file.

/** One built vehicle or option as shown on a term archive page. */
export type ProductVehicle = {
  image: string;
  alt: string;
  name: string;
  /** 特徴 copy; one entry per line. */
  description: string[];
  details: { image: string; captions: string[] }[];
};

/** A taxonomy term — "ウイング車", "床フック" and so on. */
export type ProductTerm = {
  slug: string;
  name: string;
  image: string;
  vehicles: ProductVehicle[];
};

/** Top-level grouping: ボデー or オプション. */
export type ProductCategory = {
  group: string;
  en: string;
  ja: string;
  terms: ProductTerm[];
};

export const productCategories: ProductCategory[] = ${JSON.stringify(categories, null, 2)};

export function findTerm(group: string, slug: string) {
  const category = productCategories.find((item) => item.group === group);
  const term = category?.terms.find((item) => item.slug === slug);
  return category && term ? { category, term } : undefined;
}
`;

writeFileSync(new URL("../data/products.ts", import.meta.url), file);
writeFileSync(manifestOut, [...assets].sort().join("\n") + "\n");

const termCount = categories.reduce((sum, category) => sum + category.terms.length, 0);
console.log(`data/products.ts: ${termCount} terms, ${assets.size} uploads referenced`);
